// Fisher-Yates: Array.prototype.sort with a random comparator is not
// uniformly distributed (biased by the engine's sort algorithm).
export function shuffle<T>(items: T[]): T[] {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
